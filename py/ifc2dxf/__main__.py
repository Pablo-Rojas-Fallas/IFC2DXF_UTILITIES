"""Command-line use (testing and batches):  python -m ifc2dxf input.ifc output.dxf [options]"""
import argparse
import sys

from .pipeline import Options, convert
from .report import report_text


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="ifc2dxf", description="Pipe-network IFC -> georeferenced DXF")
    ap.add_argument("ifc")
    ap.add_argument("dxf")
    ap.add_argument("--3d", dest="axes_3d", action="store_true", help="3D axes with real elevation")
    ap.add_argument("--no-texts", action="store_true", help="no data texts/attributes")
    ap.add_argument("--manhole-outlines", action="store_true", help="manholes as outlines instead of blocks")
    ap.add_argument("--single-layer", action="store_true", help="do not separate systems into layers")
    ap.add_argument("--text-height", type=float, default=0.5)
    ap.add_argument("--overwrite", action="store_true")
    ap.add_argument("--declutter", dest="declutter", action="store_true", default=True,
                    help="move pipe labels and level texts to avoid overlaps, with leader lines (default: on)")
    ap.add_argument("--no-declutter", dest="declutter", action="store_false",
                    help="keep pipe labels and level texts at their standard positions")
    ap.add_argument("--data-text-scale", type=float, default=1.0,
                    help="size factor for pipe labels and level texts only (default 1.0)")
    ap.add_argument("--short-labels", action="store_true",
                    help="abbreviate materials in pipe labels (PE, PVC, DI, DW)")
    ap.add_argument("--write-geodata", action="store_true",
                    help="write the AutoCAD geolocation object (experimental - may misplace the drawing)")
    ap.add_argument("--json", help="optional .json analysis (generated by the AI)")
    ap.add_argument("--prompt", action="store_true", help="only print the AI prompt for this IFC and exit")
    a = ap.parse_args(argv)
    if a.prompt:
        from .prompt import build
        from .summary import generate
        print(build(generate(a.ifc)))
        return 0
    opt = Options(axes_3d=a.axes_3d, data_texts=not a.no_texts, manholes_as_blocks=not a.manhole_outlines,
                  layers_per_system=not a.single_layer, text_height=a.text_height, overwrite=a.overwrite,
                  write_geodata=a.write_geodata, declutter=a.declutter, data_text_scale=a.data_text_scale,
                  short_labels=a.short_labels)
    from .analysis import read
    analysis = read(a.json) if a.json else None
    r = convert(a.ifc, a.dxf, opt, analysis=analysis, progress=lambda f, m: print(f"[{f:4.0%}] {m}", file=sys.stderr))
    if not r.ok:
        print(f"ERROR: {r.error}", file=sys.stderr)
        if r.report.get("traceback"):
            print(r.report["traceback"], file=sys.stderr)
        return 1
    print(report_text(r.report))
    return 0


if __name__ == "__main__":
    sys.exit(main())
